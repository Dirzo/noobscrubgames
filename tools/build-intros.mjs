// Ports the Siege of Legends intro animations into the site.
// Usage: node tools/build-intros.mjs ../manatorium
//   public/js/splash.js   the "NOOBSCRUB GAMES" logo skits (src/splash.js), standalone, with a tiny synth shim
//   public/sol-intro.html the full opening cinematic (src/intro.js) on the game's own engine, without the game UI
import fs from 'fs';
import path from 'path';
const game = path.resolve(process.argv[2] || '../manatorium');
const out = new URL('../public/', import.meta.url);
const read = f => fs.readFileSync(path.join(game, 'src', f), 'utf8');
const sha = (() => { try { return fs.readFileSync(path.join(game, '.git', 'HEAD'), 'utf8').trim(); } catch (e) { return 'unknown'; } })();
const banner = `// Generated by tools/build-intros.mjs from Dirzo/manatorium (${sha}). Edit the game, then rebuild.\n`;

// 1. splash: needs only pick() and a few SFX methods
const fx = read('fx.js');
const sfxStart = fx.indexOf('const SFX = {');
const playAt = fx.indexOf('  play(n)', sfxStart);
const sfxCore = fx.slice(sfxStart, playAt) + '};\n';
const splash = banner + '(function () {\nconst pick = arr => arr[Math.floor(Math.random() * arr.length)];\n' + sfxCore + read('splash.js') +
  '\nwindow.startSplash = (done, which) => { SFX.init(); if (SFX.ctx && SFX.ctx.state === "suspended") SFX.ctx.resume(); return startSplash(done, which); };\nwindow.SPLASH_SFX = SFX;\n})();\n';
fs.mkdirSync(new URL('js/', out), { recursive: true });
fs.writeFileSync(new URL('js/splash.js', out), splash);

// 2. cinematic: the game engine minus main.js and the game UI
const sources = Object.fromEntries(['fire', 'water', 'nature', 'ice', 'lightning', 'dark', 'light', 'void', 'salty', 'sweet', 'meat', 'treat'].map(el => [el, 'data:image/png;base64,' + fs.readFileSync(path.join(game, 'assets/castles/game', el + '.png')).toString('base64')]));
const mods = ['data.js', 'sprites.js', 'itemart.js', 'sim.js', 'ultkit.js', 'state.js', 'lore.js', 'achievements.js', 'fx.js', 'spellfx.js', 'bossfx.js', 'ultfx.js', 'ultfx2.js', 'render.js', 'castle.js', 'element-scenes.js', 'element-terrain.js', 'element-worlds.js', 'castle-art.js', 'tips.js', 'ui.js', 'intro.js'];
const js = 'const CASTLE_ART_SOURCES = ' + JSON.stringify(sources) + ';\n' + mods.map(read).join('\n');
const css = read('style.css');
const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<meta name="theme-color" content="#060812">
<meta name="robots" content="noindex">
<link rel="icon" href="/favicon.svg" type="image/svg+xml">
<title>Siege of Legends Intro</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Atkinson+Hyperlegible:wght@400;700&family=Fredoka:wght@400;500;600;700&family=Pixelify+Sans:wght@700&display=swap">
<style>${css}
html,body{margin:0;height:100%;background:#060812;overflow:hidden}
.sol-end{position:fixed;inset:0;display:grid;place-content:center;justify-items:center;gap:18px;text-align:center;padding:24px;opacity:0;transition:opacity .6s;pointer-events:none}
.sol-end.on{opacity:1;pointer-events:auto}
.sol-end b{font-family:var(--f-logo,'Pixelify Sans',sans-serif);font-size:clamp(34px,8vw,72px);color:#ffd84a;text-shadow:0 4px 0 #c2410c,0 8px 0 #1a1230}
.sol-end .row{display:flex;gap:12px;flex-wrap:wrap;justify-content:center}
.sol-end a,.sol-end button{font:700 15px Fredoka,system-ui,sans-serif;letter-spacing:.05em;padding:12px 20px;border:2px solid #1a1230;border-radius:6px;background:#ffd84a;color:#1a1230;box-shadow:0 4px 0 #1a1230;cursor:pointer;text-decoration:none}
.sol-end button{background:#2a2f5a;color:#e8e4ff}
</style>
</head>
<body>
<div class="sol-end" id="solEnd"><b>Siege of Legends</b><div class="row"><a href="https://manatorium.noobscrub.workers.dev" target="_top">Play now ↗</a><button type="button" id="solAgain">Watch again</button><button type="button" id="solClose">Back to site</button></div></div>
<script>
${banner}${js}
(function () {
  const end = document.getElementById('solEnd');
  const close = () => { if (parent !== window) parent.postMessage('sol-intro-close', '*'); else location.href = '/'; };
  const play = () => { end.classList.remove('on'); startIntro(() => end.classList.add('on')); };
  document.getElementById('solAgain').onclick = play;
  document.getElementById('solClose').onclick = close;
  addEventListener('keydown', e => { if (e.key === 'Escape') close(); });
  loadCastleArt().then(() => { buildAllSprites(); play(); });
})();
</script>
</body>
</html>
`;
fs.writeFileSync(new URL('sol-intro.html', out), html);
console.log('splash.js', (splash.length / 1024).toFixed(1) + ' KB; sol-intro.html', (html.length / 1024).toFixed(1) + ' KB');
